export function fitCamera(camera, bounds, target, direction) {
  const corners = [];
  if (bounds.isObject3D) {
    bounds.updateMatrixWorld(true);
    bounds.traverse(object => {
      if (!object.isMesh) return;
      const positions = object.geometry.attributes.position;
      if (positions.count > 5000) {
        for (let i = 0; i < positions.count; i += Math.max(1, Math.floor(positions.count / 4000))) corners.push(new THREE.Vector3().fromBufferAttribute(positions, i).applyMatrix4(object.matrixWorld));
        return;
      }
      object.geometry.computeBoundingBox();
      const box = object.geometry.boundingBox;
      for (const x of [box.min.x, box.max.x]) for (const y of [box.min.y, box.max.y]) for (const z of [box.min.z, box.max.z]) corners.push(new THREE.Vector3(x, y, z).applyMatrix4(object.matrixWorld));
    });
  } else for (const x of [bounds.min.x, bounds.max.x]) for (const y of [bounds.min.y, bounds.max.y]) for (const z of [bounds.min.z, bounds.max.z]) corners.push(new THREE.Vector3(x, y, z));
  let distance = 3;
  for (let i = 0; i < 8; i++) {
    camera.position.copy(direction).normalize().multiplyScalar(distance).add(target);
    camera.lookAt(target);
    camera.updateMatrixWorld();
    const extent = corners.reduce((extent, point) => { const p = point.clone().project(camera); return Math.max(extent, Math.abs(p.x) / .96, Math.abs(p.y) / .94); }, -Infinity);
    if (Math.abs(extent - 1) < .002) break;
    distance *= extent;
  }
  return distance;
}

// On narrow screens, approach the center of the ultrawide so the menu stays readable.
export function monitorView(aspect) {
  const distance = aspect < 1.2 ? .88 : 1.30 / (2 * Math.tan(THREE.MathUtils.degToRad(overview.fov / 2)) * aspect * .88);
  const target = new THREE.Vector3(...monitorScreen.center);
  return {
    position: target.clone().add(new THREE.Vector3(0, Math.sin(.42), Math.cos(.42)).multiplyScalar(distance)),
    target,
    menuWidth: Math.min(1.10, 2 * distance * Math.tan(THREE.MathUtils.degToRad(overview.fov / 2)) * aspect * .82),
  };
}
