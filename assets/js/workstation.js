  function profiledShell(w, d, radius, profile, mat, position, parent, rearWidth = 0, frontTaper = 0) {
    const rings = profile.map(([y, inset, frontCut = 0, rearCut = 0]) => {
      const x = w / 2 - inset, z = d / 2 - inset, r = radius - inset, points = [];
      for (let corner = 0; corner < 4; corner++) {
        const cx = corner === 0 || corner === 3 ? x - r : -x + r;
        const cz = corner < 2 ? z - r : -z + r;
        for (let step = 0; step <= 8; step++) {
          const a = (corner + step / 8) * Math.PI / 2;
          points.push([cx + Math.cos(a) * r, y, cz + Math.sin(a) * r]);
        }
        if (corner === 0) for (let i = 8; i >= 0; i--) {
          const px = (i / 8 * 2 - 1) * .023;
          points.push([px, y, z - frontCut * (1 + Math.cos(px / .023 * Math.PI)) / 2]);
        }
        if (frontTaper && (corner === 1 || corner === 3)) points.push([corner === 1 ? -x : x, y, .108]);
        if (corner === 2 && rearWidth) for (const t of [-1, -.96, -.91, -.86, 0, .86, .91, .96, 1]) {
          const amount = THREE.MathUtils.smoothstep(1 - Math.abs(t), 0, .14);
          points.push([t * rearWidth / 2, y, -z + rearCut * amount]);
        }
      }
      return points.map(([px, py, pz]) => [px, py + frontTaper * THREE.MathUtils.clamp((pz - .108) / (d / 2 - .108), 0, 1) * (profile.at(-1)[0] - py) / (profile.at(-1)[0] - profile[0][0]), pz]);
    });
    const vertices = rings.flat(2), uv = [], indices = [], count = rings[0].length;
    for (let row = 0; row < rings.length - 1; row++) for (let i = 0; i < count; i++) {
      const a = row * count + i, b = a + count, next = (i + 1) % count;
      indices.push(a, b, row * count + next, row * count + next, b, (row + 1) * count + next);
    }
    for (const [ring, top] of [[rings[0], false], [rings.at(-1), true]]) {
      // Preserve a flat floor up to the start of the Mouse's short front wedge.
      const faces = frontTaper && !top ? [ring.filter(([, , z]) => z <= .108), ring.filter(([, , z]) => z >= .108)] : [ring];
      for (const face of faces) {
        const start = vertices.length / 3;
        vertices.push(...face.flat());
        for (const triangle of THREE.ShapeUtils.triangulateShape(face.map(([x, , z]) => new THREE.Vector2(x, z)), [])) {
          const [a, b, c] = triangle.map(index => face[index]);
          const clockwise = (b[0] - a[0]) * (c[2] - a[2]) - (b[2] - a[2]) * (c[0] - a[0]) < 0;
          if (clockwise !== top) triangle.reverse();
          indices.push(...triangle.map(index => start + index));
        }
      }
    }
    for (let i = 0; i < vertices.length; i += 3) uv.push(vertices[i] / w + .5, .5 - vertices[i + 2] / d);
    const geometry = new THREE.BufferGeometry();
    geometry.setAttribute('position', new THREE.Float32BufferAttribute(vertices, 3));
    geometry.setAttribute('uv', new THREE.Float32BufferAttribute(uv, 2));
    geometry.setIndex(indices); geometry.computeVertexNormals();
    return add(geometry, mat, position, parent);
  }

